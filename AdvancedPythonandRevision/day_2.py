# Escape sequences:

# /" -> to include quotes in the print
# // -> To include a back slash in the print
# /n -> To start a new line

print("Project \" X \"")
print("Project \\ X")
print("Project \n X")


# formatted String

first = "Anant"
last = "Singh"

full1 = first+last
full2 = f"{first}{last}"

print(full1, "\n", full2)
